//! The Metal sources of the voice isolator's custom MLX kernels: head split with RoPE, head merge
//! with exclusive self attention, the depthwise convolution, the selective scan and GELU.
//!
//! Copied verbatim from `Sources/VoiceIsolatorMLX/KernelSources.swift` of
//! <https://github.com/starkdmi/VoiceIsolatorMLX> (Apache-2.0, Copyright 2026 Dmitry Starkov;
//! the network is Inworld AI's voice isolator, Apache-2.0). `ERF` is an erf approximation
//! adapted from MLX (MIT, Copyright 2023 Apple Inc.) after N. Juffa's faithfully rounded erff.
//! `{T}` is the activation type and `{Y}` the scan output type; `{rope}`, `{exclusive}`,
//! `{h_init}` and `{h_store}` are filled in by `crate::mlx_isolator`. Not reformatted, so a
//! diff against upstream stays readable. Generated by `scripts/sync_mlx_kernels.py`; edit that
//! script's input, not this file.

pub(crate) const TOKEN: &str = r#"
        template <typename P>
        inline uint token_of(uint row, uint pos, P p) {
          return (row / uint(p[1])) * uint(p[2]) + (row % uint(p[1])) * uint(p[3]) +
                 pos * uint(p[4]);
        }
"#;

pub(crate) const SOFTPLUS: &str = r#"
        // softplus with PyTorch's threshold of 20; log1p(exp(x)) with Kahan's
        // correction where 1 + exp(x) rounds.
        inline float softplus_t20(float x) {
          if (x > 20.0f) {
            return x;
          }
          const float e = metal::precise::exp(x);
          const float u = 1.0f + e;
          if (u == 1.0f) {
            return e;
          }
          return metal::precise::log(u) * (e / (u - 1.0f));
        }
"#;

pub(crate) const ERF: &str = r#"
        // erf after MLX's Metal erf (MIT License, Copyright 2023 Apple Inc.), from
        // N. Juffa's faithfully rounded erff; the large-argument branch takes
        // 1 - exp(r) for r <= -0.9, where it does not cancel.
        inline float vi_erf(float a) {
          const float t = metal::abs(a);
          const float s = a * a;
          float r;
          if (t > 0.927734375f) {
            r = metal::fma(-1.72853470e-5f, t, 3.83197126e-4f);
            const float u = metal::fma(-3.88396438e-3f, t, 2.42546219e-2f);
            r = metal::fma(r, s, u);
            r = metal::fma(r, t, -1.06777877e-1f);
            r = metal::fma(r, t, -6.34846687e-1f);
            r = metal::fma(r, t, -1.28717512e-1f);
            r = metal::fma(r, t, -t);
            r = 1.0f - metal::precise::exp(r);
            r = metal::copysign(r, a);
          } else {
            r = -5.96761703e-4f;
            r = metal::fma(r, s, 4.99119423e-3f);
            r = metal::fma(r, s, -2.67681349e-2f);
            r = metal::fma(r, s, 1.12819925e-1f);
            r = metal::fma(r, s, -3.76125336e-1f);
            r = metal::fma(r, s, 1.28379166e-1f);
            r = metal::fma(r, a, a);
          }
          return r;
        }
"#;

pub(crate) const SPLIT: &str = r#"
          const uint d = thread_position_in_grid.x;
          const uint h = thread_position_in_grid.y;
          const uint rp = thread_position_in_grid.z;
          const uint L = uint(params[0]);
          const uint row = rp / L;
          const uint pos = rp % L;
          constexpr uint W = H * D;
          constexpr uint HALF = D / 2;
          const device {T}* src = qkv + size_t(token_of(row, pos, params)) * 3 * W +
                                    h * D;
          const size_t dst = ((size_t(row) * H + h) * L + pos) * D;
          float q1 = src[d], q2 = src[d + HALF];
          float k1 = src[W + d], k2 = src[W + d + HALF];
        {rope}  q[dst + d] = {T}(q1);
          q[dst + d + HALF] = {T}(q2);
          k[dst + d] = {T}(k1);
          k[dst + d + HALF] = {T}(k2);
          v[dst + d] = src[2 * W + d];
          v[dst + d + HALF] = src[2 * W + d + HALF];
"#;

pub(crate) const ROPE: &str = r#"
          {
            const float c = cos_t[pos * HALF + d];
            const float s = sin_t[pos * HALF + d];
            const float qa = q1 * c - q2 * s, qb = q1 * s + q2 * c;
            const float ka = k1 * c - k2 * s, kb = k1 * s + k2 * c;
            q1 = qa; q2 = qb; k1 = ka; k2 = kb;
          }
"#;

pub(crate) const MERGE: &str = r#"
          const uint lane = thread_position_in_grid.x;
          const uint h = thread_position_in_grid.y;
          const uint rp = thread_position_in_grid.z;
          const uint L = uint(params[0]);
          const uint row = rp / L;
          const uint pos = rp % L;
          constexpr uint W = H * D;
          constexpr uint PER = D / 32;
          const size_t src = ((size_t(row) * H + h) * L + pos) * D;
          float vals[PER];
          for (uint i = 0; i < PER; ++i) {
            vals[i] = o[src + lane + 32 * i];
          }
        {exclusive}
          device {T}* dst = out + size_t(token_of(row, pos, params)) * W + h * D;
          for (uint i = 0; i < PER; ++i) {
            dst[lane + 32 * i] = {T}(vals[i]);
          }
"#;

pub(crate) const EXCLUSIVE: &str = r#"
          float num = 0.0f, den = 0.0f;
          float vv[PER];
          for (uint i = 0; i < PER; ++i) {
            vv[i] = v[src + lane + 32 * i];
            num += vals[i] * vv[i];
            den += vv[i] * vv[i];
          }
          num = simd_sum(num);
          den = simd_sum(den);
          const float coef = num / metal::max(den, 1e-6f);
          for (uint i = 0; i < PER; ++i) {
            vals[i] = vals[i] - coef * vv[i];
          }
"#;

pub(crate) const CONV: &str = r#"
          // One thread per (channel, run of P positions, direction): the taps of a
          // run are loaded once and slide along it.
          constexpr int P = 8;
          const uint c = thread_position_in_grid.x;
          const uint rr = thread_position_in_grid.y;
          const uint dir = thread_position_in_grid.z;
          const int L = params[0];
          const int runs = (L + P - 1) / P;
          const uint row = rr / uint(runs);
          const int p0 = int(rr % uint(runs)) * P;
          const uint C = uint(bias_shape[1]);
          const uint tokens = uint(params[5]);
          const uint stride = DIRS * C;
          const uint wc = dir * C + c;
          const long base = long(token_of(row, 0, params));
          const long seq = long(params[4]);
          const int n = metal::min(P, L - p0);
          float w[KW];
          for (int j = 0; j < KW; ++j) {
            w[j] = weight[wc * KW + j];
          }
          const float b = bias[wc];
          // positions are visited in scan order (forward: increasing, reverse:
          // decreasing); window[j] holds the input KW - 1 - j steps before the
          // current position in that order, window[KW - 1] the current input
          const int sgn = dir == 0 ? 1 : -1;
          const int start = dir == 0 ? p0 : p0 + n - 1;
          float window[KW];
          for (int j = 0; j < KW - 1; ++j) {
            const int at = start + sgn * (j - (KW - 1));
            float x = 0.0f;
            if (at >= 0 && at < L) {
              x = u[size_t(base + long(at) * seq) * stride + wc];
            }{history}
            window[j] = x;
          }
          for (int i = 0; i < n; ++i) {
            const int pos = start + sgn * i;
            window[KW - 1] = u[size_t(base + long(pos) * seq) * stride + wc];
            float acc = b;
            for (int j = 0; j < KW; ++j) {
              acc += w[j] * window[j];
            }
            uc[(size_t(dir) * tokens + size_t(base + long(pos) * seq)) * C + c] =
                {T}(acc / (1.0f + metal::precise::exp(-acc)));
            for (int j = 0; j < KW - 1; ++j) {
              window[j] = window[j + 1];
            }
          }
"#;

pub(crate) const SCAN: &str = r#"
          const uint c = thread_position_in_grid.x;
          const uint row = thread_position_in_grid.y;
          const uint dir = thread_position_in_grid.z;
          const int L = params[0];
          const uint C = uint(D_shape[1]);
          const uint tokens = uint(params[5]);
          const uint zstride = DIRS * C;
          const uint wc = dir * C + c;
          float a[S];
          float h[S];
          for (int s = 0; s < S; ++s) {
            a[s] = A[wc * S + s];
            h[s] = {h_init};
          }
          float w[R];
          for (int r = 0; r < R; ++r) {
            w[r] = Wdt[wc * R + r];
          }
          const float bias = bdt[wc];
          const float skip = D[wc];
          const long first = long(token_of(row, 0, params));
          const long seq = long(params[4]);
          for (int i = 0; i < L; ++i) {
            const int t = dir == 1 ? (L - 1 - i) : i;
            const size_t tok = size_t(first + long(t) * seq);
            const device {T}* p = dbc + (size_t(dir) * tokens + tok) * (R + 2 * S);
            float acc = 0.0f;
            for (int r = 0; r < R; ++r) {
              acc += float(p[r]) * w[r];
            }
            const float step = softplus_t20(acc + bias);
            const float x = uc[(size_t(dir) * tokens + tok) * C + c];
            const float drive = step * x;
            float out = 0.0f;
            for (int s = 0; s < S; ++s) {
              h[s] = metal::precise::exp(step * a[s]) * h[s] + drive * float(p[R + s]);
              out += h[s] * float(p[R + S + s]);
            }
            out += x * skip;
            const float g = z[tok * zstride + wc];
            y[tok * (DIRS * C) + wc] = {Y}(out * (g / (1.0f + metal::precise::exp(-g))));
          }{h_store}
"#;

pub(crate) const GELU: &str = r#"
          const uint i = thread_position_in_grid.x;
          const float v = float(x[i]);
          y[i] = {T}((0.5f * v) * (1.0f + vi_erf(v * 0.70710678118654752f)));
"#;
