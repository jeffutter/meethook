#!/usr/bin/env python3
"""Regenerates crates/meethook-transcribe/src/mlx_kernels.rs from VoiceIsolatorMLX's Swift.

    python3 scripts/sync_mlx_kernels.py PATH/TO/VoiceIsolatorMLX/Sources/VoiceIsolatorMLX/KernelSources.swift
    python3 scripts/sync_mlx_kernels.py KernelSources.swift --check   # exit 1 if the file differs

The Metal kernels of the voice isolator's MLX engine are copied verbatim from the upstream Swift
package (see MLX.md); this turns each `static let name = #\"\"\"...\"\"\"#` literal into a Rust
raw string constant, so updating them is one command and a reviewable diff, not hand editing.
Two upstream kernels are skipped because only the streaming (realtime) model uses them:
`convHistory` and `scanStore`. Standard library only, so it runs anywhere.
"""

import pathlib
import re
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / "crates/meethook-transcribe/src/mlx_kernels.rs"
SKIP = {"convHistory", "scanStore"}

HEADER = """//! The Metal sources of the voice isolator's custom MLX kernels: head split with RoPE, head merge
//! with exclusive self attention, the depthwise convolution, the selective scan and GELU.
//!
//! Copied verbatim from `Sources/VoiceIsolatorMLX/KernelSources.swift` of
//! <https://github.com/starkdmi/VoiceIsolatorMLX> (Apache-2.0, Copyright 2026 Dmitry Starkov;
//! the network is Inworld AI's voice isolator, Apache-2.0). `ERF` is an erf approximation
//! adapted from MLX (MIT, Copyright 2023 Apple Inc.) after N. Juffa's faithfully rounded erff.
//! `{T}` is the activation type and `{Y}` the scan output type; `{rope}`, `{exclusive}`,
//! `{h_init}` and `{h_store}` are filled in by `crate::mlx_isolator`. Not reformatted, so a
//! diff against upstream stays readable. Generated by `scripts/sync_mlx_kernels.py`; edit that
//! script's input, not this file.

"""


def render(swift: str) -> str:
    out = [HEADER]
    found = 0
    for m in re.finditer(r'static let (\w+) = #"""\n(.*?)\n\s*"""#', swift, re.S):
        name, body = m.groups()
        if name in SKIP:
            continue
        # A `"#` inside would end the Rust raw string early.
        assert '"#' not in body, f"{name} contains a raw-string terminator"
        out.append(f'pub(crate) const {name.upper()}: &str = r#"{body}\n"#;\n')
        found += 1
    if found == 0:
        sys.exit("no `static let ... = #\"\"\"` literals found: is this KernelSources.swift?")
    return "\n".join(out)


def main() -> None:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if len(args) != 1:
        sys.exit(__doc__)
    text = render(pathlib.Path(args[0]).read_text())
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
