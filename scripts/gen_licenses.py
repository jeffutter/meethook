#!/usr/bin/env python3
"""Regenerates THIRD_PARTY_LICENSES.md, the notices `meethook licenses` prints.

    python3 scripts/gen_licenses.py            # rewrite the file
    python3 scripts/gen_licenses.py --check    # exit 1 if it is out of date (CI)

Two parts, because two kinds of code end up in the binary:

- the Rust crates, from `cargo about` (config: about.toml, template: about.hbs), which reads
  cargo metadata for both release platforms and needs `cargo-about` on PATH (the dev shell has it);
- the native code that is not a crate and that `cargo about` cannot see (ONNX Runtime, MLX,
  whisper.cpp, ...), from the verbatim upstream texts in licenses/native/, listed in NATIVE below
  with the version and the way each one gets into the binary.

Standard library only. See licenses/README.md for how to update either part.
"""

