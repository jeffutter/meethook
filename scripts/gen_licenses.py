HEADER = """# Third-party licenses

meethook itself is MIT licensed (see `LICENSE`). It includes the third-party code below, under
the licenses reproduced here. Run `meethook licenses` to print this text from the binary.

This file is generated by `scripts/gen_licenses.py`; do not edit it by hand (see
`licenses/README.md`). The model weights meethook downloads at run time are separate works under
their own licenses and are not part of the binary.

"""


def native_section() -> str:
    out = ["# Native components\n\n"]
    for name, version, how, files in NATIVE:
        out.append("=" * 80 + "\n")
        out.append(f"## {name}\n\n")
        out.append(f"Version: {version}\n\n")
        out.append(f"How it is included: {how}.\n\n")
        for file in files:
            text = (NATIVE_DIR / file).read_text(encoding="utf-8", errors="replace").rstrip("\n")
            out.append(f"### {file}\n\n```\n{text}\n```\n\n")
    return "".join(out)


def rust_section() -> str:
    result = subprocess.run(
        ["cargo", "about", "generate", "--all-features", "about.hbs"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        sys.exit(f"cargo about failed (is cargo-about installed?):\n{result.stderr}")
    return result.stdout


def groups(text: str) -> dict[str, str]:
    """License groups of the Rust section, keyed by heading + crate list + hash of the text."""
    out = {}
    for chunk in text.split("=" * 80 + "\n")[1:]:
        heading = chunk.splitlines()[0]
        crates = [line for line in chunk.splitlines() if line.startswith("- ")]
        digest = hashlib.sha1(chunk.encode()).hexdigest()[:10]
        summary = f"{heading} text={digest} crates={crates}"
        out[summary] = summary
    return out


def main() -> None:
    text = HEADER + native_section() + "\n" + rust_section()
    # One trailing newline, whatever the template produced.
    text = text.rstrip("\n") + "\n"
    if "--check" in sys.argv:
        current = OUT.read_text()
        if current == text:
            print("THIRD_PARTY_LICENSES.md is up to date")
            return
        # Show what differs, per license group (heading, crates, hash of the text): CI runs this
        # on Linux, where a failure that does not reproduce on a Mac is otherwise undiagnosable
        # from the log, and a raw line diff is dominated by the license texts themselves.
        old, new = groups(current), groups(text)
        for label, only, other in (("committed only", old, new), ("generated only", new, old)):
            for key, body in only.items():
                if key not in other:
                    print(f"--- {label}: {body}", file=sys.stderr)
        sys.exit(
            "THIRD_PARTY_LICENSES.md is out of date (groups that differ above): run "
            "`python3 scripts/gen_licenses.py` and commit the result"
        )
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(text) // 1024} KiB)")


if __name__ == "__main__":
    main()
